import { readFile, writeFile } from 'node:fs/promises';

// node scripts/generate-bidi-data.mjs [path/to/DerivedBidiClass-17.0.0.txt]
const version = '17.0.0';
const source = `https://www.unicode.org/Public/${version}/ucd/extracted/DerivedBidiClass.txt`;
const response = process.argv[2] ? null : await fetch(source);
if (response && !response.ok) throw new Error(`Unicode download failed: ${response.status}`);
const input = response ? await response.text() : await readFile(process.argv[2], 'utf8');
if (!input.startsWith(`# DerivedBidiClass-${version}.txt`)) throw new Error('Unexpected Unicode data version');

// Apply @missing defaults first, then explicit records, including non-strong classes.
// 0 is non-strong, 1 is Left_To_Right (L), and 2 combines Right_To_Left (R) and Arabic_Letter (AL).
const classes = new Uint8Array(0x110000);
const rows = input.split(/\r?\n/);
for (const defaults of [true, false]) {
  const pattern = defaults
    ? /^# @missing: ([0-9A-F]+)(?:\.\.([0-9A-F]+))?; (\w+)/
    : /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (\w+)/;
  for (const row of rows) {
    const match = pattern.exec(row);
    if (!match) continue;
    const [, start, end = start, name] = match;
    const value = name === 'L' || name === 'Left_To_Right' ? 1
      : ['R', 'AL', 'Right_To_Left', 'Arabic_Letter'].includes(name) ? 2 : 0;
    classes.fill(value, parseInt(start, 16), parseInt(end, 16) + 1);
  }
}

const ranges = [];
for (let start = 0; start < classes.length;) {
  let end = start + 1;
  while (end < classes.length && classes[end] === classes[start]) end++;
  if (classes[start] !== 0) ranges.push([start, end - 1, classes[start]]);
  start = end;
}

// Each range stores the gap after the preceding range, then (length - 1) * 2 + direction.
// The low direction bit is 0 for L, 1 for R/AL; unsigned integers use seven bits per byte.
const bytes = [];
let previousEnd = -1;
for (const [start, end, direction] of ranges) {
  for (let value of [start - previousEnd - 1, (end - start) * 2 + direction - 1]) {
    while (value >= 128) {
      bytes.push((value & 127) | 128);
      value >>>= 7;
    }
    bytes.push(value);
  }
  previousEnd = end;
}
const packed = Buffer.from(bytes).toString('base64');

